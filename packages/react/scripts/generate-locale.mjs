import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import * as OpenCC from 'opencc-js';

// Conversion is build-time only. The published resources remain plain JSON.
const root = resolve(import.meta.dirname, '../src/locales');
const convert = OpenCC.Converter({ from: 'cn', to: 'twp' });
const english = JSON.parse(await readFile(resolve(root, 'en-US.json'), 'utf8'));
const chinese = JSON.parse(await readFile(resolve(root, 'zh-CN.json'), 'utf8'));
function convertTree(value) {
  if (typeof value === 'string') return convert(value);
  if (Array.isArray(value)) return value.map(convertTree);
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, convertTree(child)]));
}
function schema(value) {
  if (typeof value === 'string') return { type: 'string', description: `English: ${value}` };
  if (Array.isArray(value))
    return {
      type: 'array',
      items: { type: 'string' },
      minItems: value.length,
      maxItems: value.length,
    };
  return {
    type: 'object',
    additionalProperties: false,
    properties: Object.fromEntries(
      Object.entries(value).map(([key, child]) => [key, schema(child)]),
    ),
  };
}
function paths(value, prefix = '') {
  return Object.entries(value).flatMap(([key, child]) => {
    const name = prefix ? `${prefix}.${key}` : key;
    return typeof child === 'object' && !Array.isArray(child) ? paths(child, name) : [name];
  });
}
if (JSON.stringify(paths(english).sort()) !== JSON.stringify(paths(chinese).sort()))
  throw new Error('en-US and zh-CN must contain exactly the same translation keys.');
const outputs = {
  'zh-TW.json': convertTree(chinese),
  'schema.json': {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'Leaf UI translation resources',
    description: 'Partial resources are supported. Missing entries follow ConfigProvider.locale.',
    ...schema(english),
    properties: { $schema: { type: 'string' }, ...schema(english).properties },
  },
};
for (const [file, value] of Object.entries(outputs)) {
  const content = `${JSON.stringify(value, null, 2)}\n`;
  if (process.argv.includes('--check')) {
    if (
      JSON.stringify(JSON.parse(await readFile(resolve(root, file), 'utf8'))) !==
      JSON.stringify(value)
    )
      throw new Error(`${file} is stale; run pnpm --filter @ifhover/leaf-ui generate:locale.`);
  } else await writeFile(resolve(root, file), content);
}
console.log(`Verified ${paths(english).length} translation entries in three JSON languages.`);
const declaration = `// Generated by scripts/generate-locale.mjs from en-US.json.\nexport interface LocaleMessages {\n${Object.entries(
  english,
)
  .map(
    ([group, entries]) =>
      `  readonly ${group}: {\n${Object.entries(entries)
        .map(
          ([key, value]) =>
            `    readonly ${key}: ${Array.isArray(value) ? 'readonly string[]' : 'string'};`,
        )
        .join('\n')}\n  };`,
  )
  .join('\n')}\n}\n`;
if (process.argv.includes('--check')) {
  // Ignore line endings while retaining the generated type contract.
  if (
    (await readFile(resolve(root, 'messages.ts'), 'utf8')).replaceAll('\r\n', '\n') !== declaration
  )
    throw new Error('LocaleMessages is stale; run generate:locale.');
} else await writeFile(resolve(root, 'messages.ts'), declaration);
